/**
 * Interface & Provider Implementation
 */
class LiveRailwayProvider {
  async getStation(code) {
    const clean = String(code).trim().toUpperCase()
    try {
      const liveData = await railRadarService.getStationLive(clean)
      if (liveData && liveData.station) {
        const s = liveData.station
        const base = INDIAN_RAILWAY_STATIONS[clean] || {}
        return {
          stationCode: clean,
          stationName: s.name || base.stationName || clean,
          city: s.city || base.city || 'India',
          state: base.state || '',
          zone: base.zone || 'IR',
          division: base.division || 'IR',
          latitude: s.lat || base.latitude || 28.6139,
          longitude: s.lon || base.longitude || 77.2090,
          platforms: base.platforms || 8,
          occupiedPlatforms: Math.min(base.platforms || 8, liveData.trains?.length || 4),
          incomingTrainsCount: liveData.trains?.filter(t => t.stop?.status === 'approaching').length || base.incomingTrainsCount || 5,
          outgoingTrainsCount: liveData.trains?.filter(t => t.stop?.status === 'departed').length || base.outgoingTrainsCount || 6,
          averageDelayMinutes: base.averageDelayMinutes || 12,
          passengerDensity: base.passengerDensity || 'Moderate',
          freightTraffic: base.freightTraffic || 'Moderate',
          oheStatus: base.oheStatus || 'Stable',
          signalStatus: base.signalStatus || 'Normal',
          congestionPercentage: base.congestionPercentage || 65,
          status: base.status || 'operational',
          liveTrains: liveData.trains || [],
          dataSource: 'LIVE',
          lastUpdated: new Date().toISOString(),
        }
      }
    } catch (err) {
      logger.warn(`LiveRailwayProvider failed for station ${clean}: ${err.message}`)
    }
    return null
  }

  async getTrainRoute(trainNumber) {
    try {
      const liveRoute = await railRadarService.getTrainRoute(trainNumber)
      if (liveRoute && (liveRoute.stations?.length > 0 || liveRoute.features || liveRoute.route?.length > 0)) {
        return {
          ...liveRoute,
          dataSource: 'LIVE',
        }
      }
    } catch (err) {
      logger.warn(`LiveRailwayProvider failed for route ${trainNumber}: ${err.message}`)
    }
    return null
  }
}

class MockRailwayProvider {
  getStation(code) {
    const clean = String(code).trim().toUpperCase()
    const stn = INDIAN_RAILWAY_STATIONS[clean]
    if (!stn) return null

    return {
      ...stn,
      dataSource: 'DEMO',
      lastUpdated: new Date().toISOString(),
    }
  }

  searchStations(query = '', limit = 10) {
    const q = String(query).trim().toLowerCase()
    const all = Object.values(INDIAN_RAILWAY_STATIONS)
    if (!q) return all.slice(0, limit)
    return all
      .filter(
        (s) =>
          s.stationCode.toLowerCase().includes(q) ||
          s.stationName.toLowerCase().includes(q) ||
          s.city.toLowerCase().includes(q),
      )
      .slice(0, limit)
  }
}

export class RailwayDataProvider {
  constructor() {
    this.liveProvider = new LiveRailwayProvider()
    this.mockProvider = new MockRailwayProvider()
  }

  async getStation(code, forceLive = false) {
    const clean = String(code).trim().toUpperCase()
    if (!clean) return null

    // 1. Try live provider first
    const live = await this.liveProvider.getStation(clean)
    if (live) return live

    // 2. Fall back to mock provider
    const mock = this.mockProvider.getStation(clean)
    if (mock) return mock

    return null
  }

  searchStations(query, limit = 20) {
    return this.mockProvider.searchStations(query, limit)
  }
}

export const railwayDataProvider = new RailwayDataProvider()
